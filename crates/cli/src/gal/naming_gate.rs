    /// A temp git repo (`git init`), with `write_tracked` staging files via
    /// `git add` so [`NamingGate::scan_tree`] sees them in `git ls-files`.
    struct TempRepo {
        dir: tempfile::TempDir,
    }

    impl TempRepo {
        fn new() -> Self {
            let dir = tempfile::tempdir().expect("tempdir");
            let status = Command::new("git")
                .arg("-C")
                .arg(dir.path())
                .arg("init")
                .arg("--quiet")
                .status()
                .expect("git init spawns");
            assert!(status.success(), "git init must succeed");
            Self { dir }
        }

        fn root(&self) -> &Path {
            self.dir.path()
        }

        /// Write `rel` and `git add` it (tracked/staged, visible to `ls-files`).
        fn write_tracked(&self, rel: &str, body: impl AsRef<[u8]>) {
            self.write_untracked(rel, body);
            let status = Command::new("git")
                .arg("-C")
                .arg(self.root())
                .arg("add")
                .arg(rel)
                .status()
                .expect("git add spawns");
            assert!(status.success(), "git add must succeed for {rel}");
        }

        /// Write `rel` to disk without staging it (untracked).
        fn write_untracked(&self, rel: &str, body: impl AsRef<[u8]>) {
            let p = self.root().join(rel);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, body).unwrap();
        }
    }

    /// PNG signature + IHDR length: invalid UTF-8 at index 0, NUL at index 8,
    /// followed by a plan-task ID that must never be reported from a binary.
    const PNG_WITH_ID: &[u8] = b"\x89PNG\r\n\x1a\n\x00\x00\x00\x0dIHDR T-001\n";

    #[test]
    fn scan_staged_skips_binary_blobs_and_still_enforces_text() {
        let repo = TempRepo::new();
        repo.write_tracked("assets/logo.png", PNG_WITH_ID);
        // No NUL byte, so only `.gitattributes` marks this blob binary.
        repo.write_tracked(".gitattributes", "*.dat binary\n");
        repo.write_tracked("assets/blob.dat", b"\xff\xfe T-002\n");
        repo.write_tracked("crates/base/src/lib.rs", "// see T-003\n");

        let hits = gate()
            .scan_staged(repo.root())
            .expect("binary blobs must not fail the staged scan");
        assert_eq!(hits.len(), 1, "unexpected: {hits:?}");
        assert_eq!(hits[0].path, "crates/base/src/lib.rs");
        assert_eq!(hits[0].violations[0].matched, "T-003");
    }

    #[test]
    fn scan_staged_scans_non_utf8_text_lossily() {
        // Latin-1 text: invalid UTF-8, no NUL, no binary attribute. It is
        // text, so its ASCII plan-task ID must still be reported.
        let repo = TempRepo::new();
        repo.write_tracked("docs/legacy.txt", b"caf\xe9 T-004\n");

        let hits = gate().scan_staged(repo.root()).expect("scan succeeds");
        assert_eq!(hits.len(), 1, "unexpected: {hits:?}");
        assert_eq!(hits[0].violations[0].matched, "T-004");
    }

