function Convert-LegacyRuntimeSelection {
    param(
        [string[]]$SelectedRuntimes,
        [string]$PrimaryRuntime
    )

    $migrateGeminiToAntigravity = ($SelectedRuntimes -contains 'gemini') -and -not ($SelectedRuntimes -contains 'antigravity')
    $normalized = [System.Collections.Generic.List[string]]::new()

    foreach ($runtime in @($SelectedRuntimes)) {
        $resolvedRuntime = if ($migrateGeminiToAntigravity -and $runtime -eq 'gemini') { 'antigravity' } else { $runtime }
        if ($resolvedRuntime -notin $script:SetupContext.RuntimeCatalog.Key) { continue }
        if ($normalized -contains $resolvedRuntime) { continue }
        $normalized.Add($resolvedRuntime)
    }

    $resolvedPrimaryRuntime = if ($migrateGeminiToAntigravity -and $PrimaryRuntime -eq 'gemini') {
        'antigravity'
    }
    else {
        $PrimaryRuntime
    }

    if ($normalized -notcontains $resolvedPrimaryRuntime) {
        $resolvedPrimaryRuntime = Get-DefaultPrimaryRuntime -SelectedRuntimes $normalized
    }

    return [pscustomobject]@{
        SelectedRuntimes = @($normalized)
        PrimaryRuntime = $resolvedPrimaryRuntime
        Migrated = $migrateGeminiToAntigravity
    }
}

function ConvertFrom-MultiSelectAnswer([string]$Answer, [int]$MaxIndex) {
    $selected = [System.Collections.Generic.List[int]]::new()
    if ([string]::IsNullOrWhiteSpace($Answer)) {
        return @()
    }

    foreach ($segment in ($Answer -split ',')) {
        $trimmed = $segment.Trim()
        if ([string]::IsNullOrWhiteSpace($trimmed)) { continue }
        $number = 0
        if (-not [int]::TryParse($trimmed, [ref]$number)) {
            throw "Invalid selection '$trimmed'."
        }
        if ($number -lt 1 -or $number -gt $MaxIndex) {
            throw "Selection '$trimmed' is out of range."
        }
        if (-not $selected.Contains($number)) {
            [void]$selected.Add($number)
        }
    }

    return @($selected)
}

function Read-RuntimeSelection([object[]]$Catalog, [string[]]$DefaultSelection, [string]$PromptReason) {
    Write-Host '  [PROMPT] Select the AI runtimes where GAL should install machine-level integration.'
    if (-not [string]::IsNullOrWhiteSpace($PromptReason)) {
        Write-Host ('  [INFO] {0}' -f $PromptReason)
    }
    for ($index = 0; $index -lt $Catalog.Count; $index++) {
        $runtime = $Catalog[$index]
        Write-Host ('    {0}. {1} - {2}' -f ($index + 1), $runtime.Label, $runtime.Description)
    }

    $defaultNumbers = @()
    for ($index = 0; $index -lt $Catalog.Count; $index++) {
        if ($DefaultSelection -contains $Catalog[$index].Key) {
            $defaultNumbers += ($index + 1)
        }
    }

    while ($true) {
        $answer = Read-Host ('  [PROMPT] Enter selection numbers (for example: 1,3) [default: {0}]' -f ($defaultNumbers -join ','))
        if ([string]::IsNullOrWhiteSpace($answer)) {
            return @($DefaultSelection)
        }

        try {
            $selectedIndices = ConvertFrom-MultiSelectAnswer -Answer $answer -MaxIndex $Catalog.Count
            if ($selectedIndices.Count -eq 0) {
                Write-Host '  [WARN] Select at least one runtime.' -ForegroundColor Yellow
                continue
            }

            return @($selectedIndices | ForEach-Object { $Catalog[$_ - 1].Key })
        }
        catch {
            Write-Host ('  [WARN] {0}' -f $_.Exception.Message) -ForegroundColor Yellow
        }
    }
}

function Read-PrimaryRuntime([object[]]$Catalog, [string[]]$SelectedRuntimes, [string]$DefaultPrimaryRuntime) {
    $choices = @($Catalog | Where-Object { $SelectedRuntimes -contains $_.Key })
    Write-Host '  [PROMPT] Choose the primary runtime GAL should treat as your default entry point.'
    Write-Host '  [INFO] The repo remains the single source of truth for agents, skills, and commands; this choice affects defaults and summaries only.'
    for ($index = 0; $index -lt $choices.Count; $index++) {
        $runtime = $choices[$index]
        $marker = if ($runtime.Key -eq $DefaultPrimaryRuntime) { ' (default)' } else { '' }
        Write-Host ('    {0}. {1}{2}' -f ($index + 1), $runtime.Label, $marker)
    }

    $defaultIndex = @($choices.Key).IndexOf($DefaultPrimaryRuntime) + 1
    if ($defaultIndex -le 0) { $defaultIndex = 1 }

    while ($true) {
        $answer = Read-Host ('  [PROMPT] Enter one number [default: {0}]' -f $defaultIndex)
        if ([string]::IsNullOrWhiteSpace($answer)) {
            return $choices[$defaultIndex - 1].Key
        }

        $selectedIndex = 0
        if (-not [int]::TryParse($answer.Trim(), [ref]$selectedIndex)) {
            Write-Host '  [WARN] Enter a valid number.' -ForegroundColor Yellow
            continue
        }
        if ($selectedIndex -lt 1 -or $selectedIndex -gt $choices.Count) {
            Write-Host '  [WARN] Selection is out of range.' -ForegroundColor Yellow
            continue
        }

        return $choices[$selectedIndex - 1].Key
    }
}

function Get-DetectedRuntimeSelection {
    $context = $script:SetupContext
    $detected = [System.Collections.Generic.List[string]]::new()

    $copilotInstalled = (Test-Path $context.CopilotPluginInstallTarget) -or
        (Test-Path (Join-Path $context.CopilotPluginInstallTarget 'copilot-manifest.json')) -or
        (Test-Path $context.GalRootCopilot) -or
        (Get-ChildItem $context.AgentsTarget -Filter '*.agent.md' -File -ErrorAction SilentlyContinue | Where-Object { Test-GalRepoLink $_.FullName } | Select-Object -First 1) -or
        (Get-ChildItem $context.SkillsTarget -Directory -ErrorAction SilentlyContinue | Where-Object { Test-GalRepoLink $_.FullName } | Select-Object -First 1)
    if ($copilotInstalled) { $detected.Add('copilot') }

    $geminiInstalled = (Test-GalRepoLink $context.GalRootGemini) -or
        (Test-GalManagedFile $context.GeminiContextFile) -or
        (Get-ChildItem $context.GeminiCommandsTarget -Filter '*.toml' -File -ErrorAction SilentlyContinue | Where-Object { Test-GalManagedFile $_.FullName } | Select-Object -First 1)
    if ($geminiInstalled) { $detected.Add('gemini') }

    $antigravityInstalled = Test-GalRepoLink $context.GalRootAntigravity
    if ($antigravityInstalled) { $detected.Add('antigravity') }

    $codexInstalled = (Get-ChildItem $context.CodexSkillsTarget -Directory -ErrorAction SilentlyContinue | Where-Object { Test-GalRepoLink $_.FullName } | Select-Object -First 1)
    if ($codexInstalled) { $detected.Add('codex') }

    $openCodeInstalled =
        (Get-ChildItem $context.OpenCodeSkillsTarget -Directory -ErrorAction SilentlyContinue | Where-Object { Test-GalRepoLink $_.FullName } | Select-Object -First 1) -or
        (Get-ChildItem $context.OpenCodeAgentsTarget -Filter '*.md' -File -ErrorAction SilentlyContinue | Where-Object { Test-GalManagedFile $_.FullName } | Select-Object -First 1) -or
        (Get-ChildItem $context.OpenCodeCommandsTarget -Filter '*.md' -File -ErrorAction SilentlyContinue | Where-Object { Test-GalManagedFile $_.FullName } | Select-Object -First 1)
    if ($openCodeInstalled) { $detected.Add('opencode') }

    $claudeInstalled = Test-ClaudeLifecycleState -Context $context
    if ($claudeInstalled) { $detected.Add('claude') }

    return @($detected)
}

function Get-InstallSelectionState {
    $context = $script:SetupContext
    $state = if (Test-Path $context.InstallStateFile) { Read-JsonOrderedMap $context.InstallStateFile } else { $null }
    if ($state -is [System.Collections.IDictionary] -and -not $script:SetupOptions.Reconfigure) {
        $selected = @($state['selectedRuntimes']) | Where-Object { $_ -in $context.RuntimeCatalog.Key }
        $primary = [string]$state['primaryRuntime']
        $normalizedSelection = Convert-LegacyRuntimeSelection -SelectedRuntimes $selected -PrimaryRuntime $primary
        $selected = @($normalizedSelection.SelectedRuntimes)
        $primary = $normalizedSelection.PrimaryRuntime
        if ($selected.Count -gt 0 -and $selected -contains $primary) {
            Write-Host ''
            Write-Host '=== GAL runtime selection ==='
            Write-Host ('  [OK] Using saved install state from {0}' -f $context.InstallStateFile)
            if ($normalizedSelection.Migrated) {
                Write-Host '  [OK] Migrated saved runtime selection: gemini -> antigravity'
            }
            Write-Host ('  [OK] Selected runtimes: {0}' -f ($selected -join ', '))
            Write-Host ('  [OK] Primary runtime: {0}' -f $primary)
            if ($normalizedSelection.Migrated -and -not $script:SetupOptions.DryRun) {
                Write-JsonOrderedMap $context.InstallStateFile ([ordered]@{
                    schemaVersion = 1
                    selectedRuntimes = @($selected)
                    primaryRuntime = $primary
                    installedAt = if ($state.Contains('installedAt')) { $state['installedAt'] } else { (Get-Date -Format 'o') }
                    lastConfiguredAt = (Get-Date -Format 'o')
                })
                Write-Host ('  [OK] Updated install state: {0}' -f $context.InstallStateFile)
            }
            return [pscustomobject]@{
                SelectedRuntimes = $selected
                PrimaryRuntime = $primary
            }
        }
    }

    $detected = Get-DetectedRuntimeSelection
    $defaultSelection = if ($detected.Count -gt 0) { $detected } else { @($context.RuntimeCatalog.Key) }
    $promptReason = if ($detected.Count -gt 0) {
        'Detected a legacy GAL machine install without install-state. Confirm or change the runtime set before continuing.'
    }
    else {
        'First-time GAL install detected. Choose where GAL should install runtime integrations.'
    }

    Write-Host ''
    Write-Host '=== GAL runtime selection ==='
    $selectedRuntimes = Read-RuntimeSelection -Catalog $context.RuntimeCatalog -DefaultSelection $defaultSelection -PromptReason $promptReason
    $defaultPrimaryRuntime = if ($state -is [System.Collections.IDictionary] -and ($selectedRuntimes -contains [string]$state['primaryRuntime'])) {
        [string]$state['primaryRuntime']
    }
    else {
        Get-DefaultPrimaryRuntime -SelectedRuntimes $selectedRuntimes
    }
    $primaryRuntime = Read-PrimaryRuntime -Catalog $context.RuntimeCatalog -SelectedRuntimes $selectedRuntimes -DefaultPrimaryRuntime $defaultPrimaryRuntime

    if (-not $script:SetupOptions.DryRun) {
        Write-JsonOrderedMap $context.InstallStateFile ([ordered]@{
            schemaVersion = 1
            selectedRuntimes = @($selectedRuntimes)
            primaryRuntime = $primaryRuntime
            installedAt = if ($state -is [System.Collections.IDictionary] -and $state.Contains('installedAt')) { $state['installedAt'] } else { (Get-Date -Format 'o') }
            lastConfiguredAt = (Get-Date -Format 'o')
        })
        Write-Host ('  [OK] Saved install state: {0}' -f $context.InstallStateFile)
    }
    else {
        Write-Host ('  [DRY RUN] Would save install state: {0}' -f $context.InstallStateFile)
    }

    return [pscustomobject]@{
        SelectedRuntimes = @($selectedRuntimes)
        PrimaryRuntime = $primaryRuntime
    }
}

function Ensure-SetupDirectories([string[]]$Directories) {
    if ($script:SetupOptions.Uninstall) { return }

    foreach ($dir in ($Directories | Select-Object -Unique)) {
        if ([string]::IsNullOrWhiteSpace($dir) -or (Test-Path $dir)) { continue }

        if ($script:SetupOptions.DryRun) {
            Write-Host "[DRY RUN] Would create directory: $dir"
        }
        else {
            New-Item -ItemType Directory -Path $dir -Force | Out-Null
            Write-Host "[OK] Created directory: $dir"
        }
    }
}

function Read-ExecutorRouting {
    $canonicalPath = Join-Path (Get-GalUserHome) '.gal\config\executor-routing.json'
    if (-not (Test-Path $canonicalPath)) {
        return $null
    }

    try {
        $parsed = Get-Content $canonicalPath -Raw -Encoding UTF8 | ConvertFrom-Json
    }
    catch {
        return $null
    }

    $routing = @{}
    foreach ($prop in $parsed.PSObject.Properties) {
        if ($prop.Name.StartsWith('_')) { continue }
        $entry = $prop.Value
        $routing[$prop.Name] = @{
            executor = if ($entry.executor) { [string]$entry.executor } else { $null }
            model    = if ($null -ne $entry.model -and $entry.model -ne '') { [string]$entry.model } else { $null }
        }
    }

    return $routing
}

