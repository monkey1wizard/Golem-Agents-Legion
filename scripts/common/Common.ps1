        return $false
    }

    return $true
}

function Initialize-SetupSession {
    param(
        [string]$EntryScriptPath,
        [switch]$Uninstall,
        [switch]$Replace,
        [switch]$DryRun,
        [switch]$Reconfigure,
        [string[]]$SelectedRuntimes,
        [string]$PrimaryRuntime,
        [switch]$EnsureRipgrep
    )

    $script:SetupOptions = [pscustomobject]@{
        Uninstall = $Uninstall.IsPresent
        Replace = $Replace.IsPresent
        DryRun = $DryRun.IsPresent
        Reconfigure = $Reconfigure.IsPresent
    }
    $script:SetupContext = New-SetupContext -EntryScriptPath $EntryScriptPath

    if (-not $script:SetupOptions.Uninstall -and $EnsureRipgrep) {
        Ensure-Ripgrep
    }

    if ($script:SetupOptions.Uninstall) {
        $script:SetupContext | Add-Member -NotePropertyName SelectedRuntimes -NotePropertyValue @() -Force
        $script:SetupContext | Add-Member -NotePropertyName PrimaryRuntime -NotePropertyValue $null -Force
    }
    else {
        if ($SelectedRuntimes.Count -gt 0) {
            $resolvedPrimaryRuntime = if ([string]::IsNullOrWhiteSpace($PrimaryRuntime)) {
                Get-DefaultPrimaryRuntime -SelectedRuntimes $SelectedRuntimes
            }
            else {
                $PrimaryRuntime
            }

            $script:SetupContext | Add-Member -NotePropertyName SelectedRuntimes -NotePropertyValue @($SelectedRuntimes) -Force
            $script:SetupContext | Add-Member -NotePropertyName PrimaryRuntime -NotePropertyValue $resolvedPrimaryRuntime -Force
        }
        else {
            $installSelection = Get-InstallSelectionState
            $script:SetupContext | Add-Member -NotePropertyName SelectedRuntimes -NotePropertyValue @($installSelection.SelectedRuntimes) -Force
            $script:SetupContext | Add-Member -NotePropertyName PrimaryRuntime -NotePropertyValue $installSelection.PrimaryRuntime -Force
        }
    }

    $selectedRuntimes = @($script:SetupContext.SelectedRuntimes)
    $script:SetupContext | Add-Member -NotePropertyName InstallCopilot -NotePropertyValue ($selectedRuntimes -contains 'copilot') -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallGemini -NotePropertyValue ($selectedRuntimes -contains 'gemini') -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallAntigravity -NotePropertyValue ($selectedRuntimes -contains 'antigravity') -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallCodex -NotePropertyValue ($selectedRuntimes -contains 'codex') -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallOpenCode -NotePropertyValue ($selectedRuntimes -contains 'opencode') -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallClaude -NotePropertyValue ($selectedRuntimes -contains 'claude') -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallSharedSkills -NotePropertyValue (($selectedRuntimes -contains 'codex') -or ($selectedRuntimes -contains 'opencode')) -Force
    $script:SetupContext | Add-Member -NotePropertyName InstallGoogleWorkspaceSkills -NotePropertyValue (($selectedRuntimes -contains 'gemini') -or ($selectedRuntimes -contains 'antigravity')) -Force
    $script:SetupContext | Add-Member -NotePropertyName NeedsBakedCommandSkills -NotePropertyValue (
        ($selectedRuntimes -contains 'copilot') -or
        ($selectedRuntimes -contains 'gemini') -or
        ($selectedRuntimes -contains 'antigravity') -or
        ($selectedRuntimes -contains 'codex') -or
        ($selectedRuntimes -contains 'opencode') -or
        ($selectedRuntimes -contains 'claude')
    ) -Force

    return $script:SetupContext
}

