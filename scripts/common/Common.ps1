function Test-ClaudeLifecycleState {
    param(
        [pscustomobject]$Context
    )

    $statePath = Get-ClaudeLifecycleStatePath -Context $Context
    if (-not (Test-Path $statePath)) {
        return $false
    }

    $state = Read-JsonOrderedMap $statePath
