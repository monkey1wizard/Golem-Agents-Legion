        Where-Object {
            $_.Name -ne 'gal' -and (
                (Test-Path (Join-Path $_.FullName 'SKILL.template.md')) -or
                (Test-Path (Join-Path $_.FullName 'SKILL.md'))
            )
        } |
        Select-Object -ExpandProperty Name

