write_install_state() {
    local selected_csv="$1"
    local primary_runtime="$2"
    local installed_at="$3"
    local configured_at="$4"

    if $DRY_RUN; then
        echo "  [DRY RUN] Would save install state: $INSTALL_STATE_FILE"
        return 0
    fi

    mkdir -p "$GAL_STATE_ROOT"
    if resolve_python_command; then
        run_python - "$INSTALL_STATE_FILE" "$selected_csv" "$primary_runtime" "$installed_at" "$configured_at" <<'PY'
import json
import sys
from pathlib import Path

path = Path(sys.argv[1])
selected = [item for item in sys.argv[2].split(',') if item]
data = {
    'schemaVersion': 1,
    'selectedRuntimes': selected,
    'primaryRuntime': sys.argv[3],
    'installedAt': sys.argv[4],
    'lastConfiguredAt': sys.argv[5],
}
path.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
PY
    else
        printf '{\n  "schemaVersion": 1,\n  "selectedRuntimes": ["%s"],\n  "primaryRuntime": "%s",\n  "installedAt": "%s",\n  "lastConfiguredAt": "%s"\n}\n' "${selected_csv//,/\", \"}" "$primary_runtime" "$installed_at" "$configured_at" > "$INSTALL_STATE_FILE"
    fi

    echo "  [OK] Saved install state: $INSTALL_STATE_FILE"
}

detect_installed_runtimes() {
    local detected=()

    if [ -e "$COPILOT_PLUGIN_INSTALL_TARGET" ] || [ -f "$COPILOT_PLUGIN_INSTALL_TARGET/copilot-manifest.json" ] || [ -e "$GAL_ROOT_COPILOT" ] || has_gal_repo_link_in_dir "$AGENTS_TARGET" || has_gal_repo_link_in_dir "$SKILLS_TARGET"; then
        detected+=(copilot)
    fi

    if is_gal_repo_link "$GAL_ROOT_GEMINI" || is_gal_managed_file "$GEMINI_CONTEXT_FILE" || has_gal_managed_file_in_dir "$GEMINI_COMMANDS_TARGET" '*.toml'; then
        detected+=(gemini)
    fi

    if is_gal_repo_link "$GAL_ROOT_ANTIGRAVITY"; then
        detected+=(antigravity)
    fi

    if has_gal_repo_link_in_dir "$CODEX_SKILLS_TARGET"; then
        detected+=(codex)
    fi

    if has_gal_repo_link_in_dir "$OPENCODE_SKILLS_TARGET" || has_gal_managed_file_in_dir "$OPENCODE_AGENTS_TARGET" '*.md' || has_gal_managed_file_in_dir "$OPENCODE_COMMANDS_TARGET" '*.md'; then
        detected+=(opencode)
    fi

    if has_claude_lifecycle_state; then
        detected+=(claude)
    fi

    join_by , "${detected[@]}"
}

parse_selection() {
    local answer="$1"
    local max_index="$2"
    local selected=()

    [ -z "$(printf '%s' "$answer" | xargs || true)" ] && {
        printf '%s\n' ''
        return 0
    }

    local item
    IFS=',' read -r -a parts <<< "$answer"
    for item in "${parts[@]}"; do
        item="$(printf '%s' "$item" | xargs)"
        [ -z "$item" ] && continue
        case "$item" in
            *[!0-9]*)
                echo "Invalid selection '$item'." >&2
                return 1
                ;;
        esac
        if [ "$item" -lt 1 ] || [ "$item" -gt "$max_index" ]; then
            echo "Selection '$item' is out of range." >&2
            return 1
        fi
        if ! contains_value "$item" "${selected[@]}"; then
            selected+=("$item")
        fi
    done

    join_by ' ' "${selected[@]}"
}

