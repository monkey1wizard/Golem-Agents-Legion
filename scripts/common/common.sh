    local default_numbers=()
    local runtime
    for runtime in ${default_selection//,/ }; do
        local number
        number="$(runtime_index "$runtime" 2>/dev/null || true)"
        [ -n "$number" ] && default_numbers+=("$((number + 1))")
    done

    while true; do
        local answer parsed
        local result=()
        read -r -p "  [PROMPT] Enter selection numbers (for example: 1,3) [default: $(join_by , "${default_numbers[@]}")]: " answer
        if [ -z "$(printf '%s' "$answer" | xargs || true)" ]; then
            printf '%s\n' "$default_selection"
            return 0
        fi
        if parsed="$(parse_selection "$answer" "${#RUNTIME_KEYS[@]}")"; then
            [ -z "$parsed" ] && {
                echo "  [WARN] Select at least one runtime." >&2
                continue
            }
            for index in $parsed; do
                result+=("${RUNTIME_KEYS[$((index - 1))]}")
            done
            printf '%s\n' "$(normalize_runtime_csv "$(join_by ' ' "${result[@]}")")"
            return 0
        fi
        echo "  [WARN] Invalid selection. Please try again." >&2
    done
}

read_primary_runtime() {
    local selected_csv="$1"
    local default_primary="$2"
    local selected=( ${selected_csv//,/ } )
    local choice_keys=()
    local default_index=1
    local index=1
    local runtime

    echo "  [PROMPT] Choose the primary runtime GAL should treat as your default entry point." >&2
    echo "  [INFO] The repo remains the single source of truth for agents, skills, and commands; this choice affects defaults and summaries only." >&2

    for runtime in "${selected[@]}"; do
        local runtime_pos marker
        runtime_pos="$(runtime_index "$runtime")"
        marker=''
        if [ "$runtime" = "$default_primary" ]; then
            marker=' (default)'
            default_index="$index"
        fi
        printf '    %s. %s%s\n' "$index" "${RUNTIME_LABELS[$runtime_pos]}" "$marker" >&2
        choice_keys+=("$runtime")
        index=$((index + 1))
    done

    while true; do
        local answer
        read -r -p "  [PROMPT] Enter one number [default: $default_index]: " answer
        if [ -z "$(printf '%s' "$answer" | xargs || true)" ]; then
            printf '%s\n' "${choice_keys[$((default_index - 1))]}"
            return 0
        fi
        case "$answer" in
            *[!0-9]*)
                echo "  [WARN] Enter a valid number." >&2
                continue
                ;;
        esac
        if [ "$answer" -lt 1 ] || [ "$answer" -gt "${#choice_keys[@]}" ]; then
            echo "  [WARN] Selection is out of range." >&2
            continue
        fi
        printf '%s\n' "${choice_keys[$((answer - 1))]}"
        return 0
    done
}

resolve_install_selection() {
    if [ -n "$SELECTED_RUNTIMES_CSV" ] && [ -n "$PRIMARY_RUNTIME" ]; then
        SELECTED_RUNTIMES_CSV="$(normalize_runtime_csv "$SELECTED_RUNTIMES_CSV")"
        if [[ ",$SELECTED_RUNTIMES_CSV," != *",$PRIMARY_RUNTIME,"* ]]; then
            PRIMARY_RUNTIME="$(default_primary_runtime ${SELECTED_RUNTIMES_CSV//,/ })"
        fi
        return 0
    fi

    local saved_selected_raw=''
    local saved_selected=''
    local saved_primary=''
    local saved_installed_at=''

    if [ -f "$INSTALL_STATE_FILE" ] && ! $RECONFIGURE; then
        saved_selected_raw="$(read_install_state_value selectedRuntimes 2>/dev/null || true)"
        saved_selected="$(normalize_runtime_csv "$saved_selected_raw")"
        local migrated_selected
        migrated_selected="$(upgrade_legacy_runtime_csv "$saved_selected")"
        saved_primary="$(read_install_state_value primaryRuntime 2>/dev/null || true)"
        saved_installed_at="$(read_install_state_value installedAt 2>/dev/null || true)"
        if [ "$saved_primary" = 'gemini' ] && [[ ",$saved_selected," != *",antigravity,"* ]] && [[ ",$migrated_selected," == *",antigravity,"* ]]; then
            saved_primary='antigravity'
        fi
        if [ -n "$migrated_selected" ] && [ -n "$saved_primary" ]; then
            echo ''
            echo '=== GAL runtime selection ==='
            echo "  [OK] Using saved install state from $INSTALL_STATE_FILE"
            if [ "$migrated_selected" != "$saved_selected" ]; then
                echo '  [OK] Migrated saved runtime selection: gemini -> antigravity'
            fi
            echo "  [OK] Selected runtimes: $(format_runtime_csv "$migrated_selected")"
            echo "  [OK] Primary runtime: $saved_primary"
            SELECTED_RUNTIMES_CSV="$migrated_selected"
            PRIMARY_RUNTIME="$saved_primary"
            if [ "$migrated_selected" != "$saved_selected_raw" ] || [ "$saved_primary" != "$(read_install_state_value primaryRuntime 2>/dev/null || true)" ]; then
                local configured_at
                configured_at="$saved_installed_at"
                [ -z "$configured_at" ] && configured_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
                write_install_state "$migrated_selected" "$saved_primary" "$configured_at" "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
            fi
            return 0
        fi
    fi

    local detected_csv default_selection prompt_reason
    detected_csv="$(detect_installed_runtimes)"
    default_selection="$detected_csv"
    prompt_reason='Detected a legacy GAL machine install without install-state. Confirm or change the runtime set before continuing.'

    if [ -z "$default_selection" ]; then
        default_selection="$(join_by , "${RUNTIME_KEYS[@]}")"
        prompt_reason='First-time GAL install detected. Choose where GAL should install runtime integrations.'
    fi

    echo ''
    echo '=== GAL runtime selection ==='
    SELECTED_RUNTIMES_CSV="$(normalize_runtime_csv "$(read_runtime_selection "$default_selection" "$prompt_reason")")"

    local default_primary="$saved_primary"
    if [ -z "$default_primary" ] || [[ ",$SELECTED_RUNTIMES_CSV," != *",$default_primary,"* ]]; then
        default_primary="$(default_primary_runtime ${SELECTED_RUNTIMES_CSV//,/ })"
    fi
    PRIMARY_RUNTIME="$(read_primary_runtime "$SELECTED_RUNTIMES_CSV" "$default_primary")"

    local configured_at installed_at
    configured_at="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    installed_at="$saved_installed_at"
    [ -z "$installed_at" ] && installed_at="$configured_at"
    write_install_state "$SELECTED_RUNTIMES_CSV" "$PRIMARY_RUNTIME" "$installed_at" "$configured_at"
}

ensure_ripgrep() {
    $UNINSTALL && return 0

    echo ''
    echo '=== ripgrep (rg) ==='

    if command_exists rg; then
        echo '  [OK] rg available'
        return 0
    fi

    if $DRY_RUN; then
        echo '  [DRY RUN] rg missing. Would prompt to install ripgrep if a supported package manager is available.'
        return 0
    fi

    local answer=''
    if [[ "${OSTYPE:-}" == darwin* ]] && command_exists brew; then
        read -r -p '  [PROMPT] ripgrep (rg) was not found. Install it now via Homebrew? [Y/n] ' answer
        case "$(printf '%s' "$answer" | tr '[:upper:]' '[:lower:]')" in
            n|no) echo '  [SKIP] ripgrep installation skipped'; return 0 ;;
        esac
        brew install ripgrep || { echo '  [WARN] ripgrep installation failed'; return 0; }
    elif command_exists apt-get; then
        read -r -p '  [PROMPT] ripgrep (rg) was not found. Install it now via apt-get? [Y/n] ' answer
        case "$(printf '%s' "$answer" | tr '[:upper:]' '[:lower:]')" in
            n|no) echo '  [SKIP] ripgrep installation skipped'; return 0 ;;
        esac
        sudo apt-get update && sudo apt-get install -y ripgrep || { echo '  [WARN] ripgrep installation failed'; return 0; }
    elif command_exists dnf; then
        read -r -p '  [PROMPT] ripgrep (rg) was not found. Install it now via dnf? [Y/n] ' answer
        case "$(printf '%s' "$answer" | tr '[:upper:]' '[:lower:]')" in
            n|no) echo '  [SKIP] ripgrep installation skipped'; return 0 ;;
        esac
        sudo dnf install -y ripgrep || { echo '  [WARN] ripgrep installation failed'; return 0; }
    elif command_exists pacman; then
        read -r -p '  [PROMPT] ripgrep (rg) was not found. Install it now via pacman? [Y/n] ' answer
        case "$(printf '%s' "$answer" | tr '[:upper:]' '[:lower:]')" in
            n|no) echo '  [SKIP] ripgrep installation skipped'; return 0 ;;
        esac
        sudo pacman -Sy --noconfirm ripgrep || { echo '  [WARN] ripgrep installation failed'; return 0; }
    else
        echo '  [WARN] rg not found and no supported package manager was detected. Install ripgrep manually, then reopen the terminal.'
        return 0
    fi

    if command_exists rg; then
        echo '  [OK] ripgrep installed and available'
    else
        echo '  [WARN] ripgrep was installed, but this shell still cannot resolve rg. Open a new terminal and rerun your command.'
    fi
}

