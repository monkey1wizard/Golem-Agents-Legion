normalize_runtime_csv() {
    local raw="$1"
    local normalized=()
    local token

    for token in $(printf '%s' "$raw" | tr ',' ' '); do
        if ! contains_value "$token" "${RUNTIME_KEYS[@]}"; then
            continue
        fi
        if contains_value "$token" "${normalized[@]}"; then
            continue
        fi
        normalized+=("$token")
    done

    join_by , "${normalized[@]}"
}

upgrade_legacy_runtime_csv() {
    local raw="$1"
    local tokens=()
    local normalized=()
    local token
    local has_antigravity=false

    for token in $(printf '%s' "$raw" | tr ',' ' '); do
        [ -n "$token" ] || continue
        tokens+=("$token")
        if [ "$token" = 'antigravity' ]; then
            has_antigravity=true
        fi
    done

    for token in "${tokens[@]}"; do
        if [ "$token" = 'gemini' ] && ! $has_antigravity; then
            token='antigravity'
        fi
        if ! contains_value "$token" "${RUNTIME_KEYS[@]}"; then
            continue
        fi
        if contains_value "$token" "${normalized[@]}"; then
            continue
        fi
        normalized+=("$token")
    done

    join_by , "${normalized[@]}"
}

