join_by() {
    local delimiter="$1"
    shift || true

    local item
    local output=""
    local first=true
    for item in "$@"; do
        if $first; then
            output="$item"
            first=false
        else
            output+="$delimiter$item"
        fi
    done

    printf '%s' "$output"
}

