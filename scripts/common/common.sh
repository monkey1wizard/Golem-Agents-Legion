contains_value() {
    local needle="$1"
    shift || true

    local item
    for item in "$@"; do
        [ "$item" = "$needle" ] && return 0
    done

    return 1
}

command_exists() {
    command -v "$1" >/dev/null 2>&1
}

PYTHON_CMD=''
PYTHON_MODE=''

resolve_python_command() {
    if [ -n "$PYTHON_CMD" ]; then
        return 0
    fi

    if command_exists python3 && python3 -c 'import sys' >/dev/null 2>&1; then
        PYTHON_CMD='python3'
        PYTHON_MODE='direct'
        return 0
    fi

    if command_exists python && python -c 'import sys' >/dev/null 2>&1; then
        PYTHON_CMD='python'
        PYTHON_MODE='direct'
        return 0
    fi

    if command_exists py && py -3 -c 'import sys' >/dev/null 2>&1; then
        PYTHON_CMD='py'
        PYTHON_MODE='launcher'
        return 0
    fi

    PYTHON_CMD=''
    PYTHON_MODE=''
    return 1
}

run_python() {
    if ! resolve_python_command; then
        return 1
    fi

    if [ "$PYTHON_MODE" = 'launcher' ]; then
        "$PYTHON_CMD" -3 "$@"
        return $?
    fi

    "$PYTHON_CMD" "$@"
}

parse_setup_args() {
    BOOTSTRAP_INSTALL=false
    UNINSTALL=false
    PURGE=false
    CONFIRM_PURGE=false
    REPLACE=false
    DRY_RUN=false
    CHECK_ONLY=false
    RECONFIGURE=false
    SELECTED_RUNTIMES_CSV=""
    PRIMARY_RUNTIME=""

    while [ "$#" -gt 0 ]; do
        case "$1" in
            --uninstall) UNINSTALL=true ;;
            --purge) PURGE=true ;;
            --confirm-purge) CONFIRM_PURGE=true ;;
            --bootstrap-install) BOOTSTRAP_INSTALL=true ;;
            --replace) REPLACE=true ;;
            --dry-run) DRY_RUN=true ;;
            --check|--doctor) CHECK_ONLY=true ;;
            --reconfigure) RECONFIGURE=true ;;
            --selected-runtimes)
                shift
                if [ "$#" -eq 0 ]; then
                    echo "Missing value for --selected-runtimes" >&2
                    exit 1
                fi
                SELECTED_RUNTIMES_CSV="$1"
                ;;
            --selected-runtimes=*)
                SELECTED_RUNTIMES_CSV="${1#*=}"
                ;;
            --primary-runtime)
                shift
                if [ "$#" -eq 0 ]; then
                    echo "Missing value for --primary-runtime" >&2
                    exit 1
                fi
                PRIMARY_RUNTIME="$1"
                ;;
            --primary-runtime=*)
                PRIMARY_RUNTIME="${1#*=}"
                ;;
            *)
                echo "Unknown argument: $1" >&2
                exit 1
                ;;
        esac
        shift
    done
}

