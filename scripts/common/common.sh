is_gal_repo_link() {
    local path="$1"
    local target_fragment="${2:-$REPO_ROOT}"
    [ -L "$path" ] || return 1

    local target
    target="$(readlink "$path" 2>/dev/null || true)"
    [ -n "$target" ] || return 1

    [[ "$target" == *"$target_fragment"* ]]
}

is_gal_command_link() {
    local path="$1"
    [ -L "$path" ] || return 1

    local target
    target="$(readlink "$path" 2>/dev/null || true)"
    [ -n "$target" ] || return 1

    [[ "$target" == *"$REPO_ROOT"*"/commands/"* ]]
}

has_gal_repo_link_in_dir() {
    local dir="$1"
    [ -d "$dir" ] || return 1

    local path
    while IFS= read -r -d '' path; do
        if is_gal_repo_link "$path"; then
            return 0
        fi
    done < <(find "$dir" -maxdepth 1 -type l -print0 2>/dev/null)

    return 1
}

has_gal_managed_file_in_dir() {
    local dir="$1"
    local pattern="$2"
    [ -d "$dir" ] || return 1

    local path
    while IFS= read -r -d '' path; do
        if is_gal_managed_file "$path"; then
            return 0
        fi
    done < <(find "$dir" -maxdepth 1 -type f -name "$pattern" -print0 2>/dev/null)

    return 1
}

